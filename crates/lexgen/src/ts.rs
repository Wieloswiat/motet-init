//! TypeScript output: one module per lexicon document plus an index.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use anyhow::Result;

use crate::{Def, Doc, Field, Object, Target, module_name, type_name};

const HEADER: &str = "// @generated by motet-lexgen from lexicons/. Do not edit; run `lexgen` in the dev shell.\n";

pub fn generate(docs: &BTreeMap<String, Doc>) -> Result<Vec<(String, String)>> {
    let mut files = Vec::new();
    let mut index = String::from(HEADER);
    index.push('\n');
    for doc in docs.values() {
        let module = module_name(&doc.id);
        let _ = writeln!(index, "export * as {module} from './{module}.js';");
        files.push((format!("{module}.ts"), document(doc)));
    }
    files.push(("index.ts".to_owned(), index));
    Ok(files)
}

fn document(doc: &Doc) -> String {
    let mut body = String::new();
    let mut imports: BTreeSet<String> = BTreeSet::new();
    let mut uses_blob = false;
    for (name, def) in &doc.defs {
        body.push('\n');
        match def {
            Def::Record { description, record, .. } => {
                let ty = type_name(&doc.id, name);
                let _ = writeln!(body, "export const {ty}Nsid = '{}' as const;\n", doc.id);
                object(&mut body, doc, &ty, description.as_deref(), record, Some(&doc.id), &mut imports, &mut uses_blob);
            }
            Def::Object(o) => {
                object(&mut body, doc, &type_name(&doc.id, name), o.description.as_deref(), o, None, &mut imports, &mut uses_blob);
            }
            Def::Unsupported => {}
        }
    }
    let mut out = String::from(HEADER);
    if uses_blob {
        out.push_str("\nimport type { Blob, CidLink } from '../atproto.js';\n");
    }
    for module in &imports {
        let _ = writeln!(out, "import type * as {module} from './{module}.js';");
    }
    out.push_str(&body);
    out
}

#[allow(clippy::too_many_arguments)]
fn object(
    out: &mut String,
    doc: &Doc,
    ty: &str,
    description: Option<&str>,
    o: &Object,
    record: Option<&str>,
    imports: &mut BTreeSet<String>,
    uses_blob: &mut bool,
) {
    doc_comment(out, "", description.or(o.description.as_deref()));
    let _ = writeln!(out, "export interface {ty} {{");
    if let Some(nsid) = record {
        let _ = writeln!(out, "  $type: '{nsid}';");
    }
    for (name, field) in &o.properties {
        doc_comment(out, "  ", field.description());
        let optional = if o.required.contains(name) { "" } else { "?" };
        let _ = writeln!(out, "  {name}{optional}: {};", ts_type(doc, field, imports, uses_blob));
    }
    out.push_str("  /** Fields this version of Motet doesn't know. Kept and written back unchanged. */\n");
    out.push_str("  [extra: string]: unknown;\n}\n");
}

fn ts_type(doc: &Doc, field: &Field, imports: &mut BTreeSet<String>, uses_blob: &mut bool) -> String {
    match field {
        Field::String { .. } => "string".to_owned(),
        Field::Integer { .. } => "number".to_owned(),
        Field::Boolean { .. } => "boolean".to_owned(),
        Field::Blob { .. } => {
            *uses_blob = true;
            "Blob".to_owned()
        }
        Field::CidLink { .. } => {
            *uses_blob = true;
            "CidLink".to_owned()
        }
        Field::Unknown { .. } => "unknown".to_owned(),
        Field::Ref { target, .. } => {
            let t = Target::resolve(&doc.id, target);
            let name = type_name(&t.doc, &t.def);
            if t.doc == doc.id {
                name
            } else {
                let module = module_name(&t.doc);
                imports.insert(module.clone());
                format!("{module}.{name}")
            }
        }
        Field::Array { items, .. } => format!("{}[]", ts_type(doc, items, imports, uses_blob)),
    }
}

fn doc_comment(out: &mut String, indent: &str, text: Option<&str>) {
    if let Some(text) = text {
        let _ = writeln!(out, "{indent}/** {} */", text.replace("*/", "*\\/"));
    }
}
