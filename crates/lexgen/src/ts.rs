//! TypeScript output: one module per lexicon document plus an index.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::{BodySchema, Def, Doc, Field, Object, Rpc, Target, module_name, type_name};

const HEADER: &str = "// @generated by motet-lexgen from lexicons/. Do not edit; run `lexgen` in the dev shell.\n";

#[must_use]
pub fn generate(docs: &BTreeMap<String, Doc>) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut index = String::from(HEADER);
    index.push('\n');
    for doc in docs.values() {
        let module = module_name(&doc.id);
        let _ = writeln!(index, "export * as {module} from './{module}.js';");
        files.push((format!("{module}.ts"), document(doc)));
    }
    files.push(("index.ts".to_owned(), index));
    files
}

fn document(doc: &Doc) -> String {
    let mut body = String::new();
    let mut imports: BTreeSet<String> = BTreeSet::new();
    let mut protocol = BTreeSet::new();
    for (name, def) in &doc.defs {
        body.push('\n');
        match def {
            Def::Record {
                description, record, ..
            } => {
                let ty = type_name(&doc.id, name);
                let _ = writeln!(body, "export const {ty}Nsid = '{}' as const;\n", doc.id);
                object(
                    &mut body,
                    doc,
                    &ty,
                    description.as_deref(),
                    record,
                    Some(&doc.id),
                    &mut imports,
                    &mut protocol,
                );
            }
            Def::Object(o) => {
                object(
                    &mut body,
                    doc,
                    &type_name(&doc.id, name),
                    o.description.as_deref(),
                    o,
                    None,
                    &mut imports,
                    &mut protocol,
                );
            }
            Def::String {
                description,
                known_values,
            } => {
                doc_comment(&mut body, "", description.as_deref());
                if !known_values.is_empty() {
                    doc_comment(
                        &mut body,
                        "",
                        Some(&format!("Known values (not exhaustive): {known_values:?}.")),
                    );
                }
                let _ = writeln!(body, "export type {} = string;", type_name(&doc.id, name));
            }
            Def::Token { description } => {
                doc_comment(&mut body, "", description.as_deref());
                let ty = type_name(&doc.id, name);
                let identifier = Target::resolve(&doc.id, &format!("#{name}")).reference();
                let _ = writeln!(body, "export const {ty} = '{identifier}' as const;");
                let _ = writeln!(body, "export type {ty} = typeof {ty};");
            }
            Def::Space { description } | Def::PermissionSet { description } => {
                doc_comment(&mut body, "", description.as_deref());
                body.push_str("/** Host policy metadata, not a wire value; no data type is generated. The vendored schema is authoritative. */\n");
                let _ = writeln!(
                    body,
                    "export const {}Nsid = '{}' as const;",
                    type_name(&doc.id, name),
                    doc.id
                );
            }
            Def::Query(rpc) | Def::Procedure(rpc) => {
                method(&mut body, doc, name, rpc, &mut imports, &mut protocol);
            }
            Def::Unsupported => {}
        }
    }
    let mut out = String::from(HEADER);
    if !protocol.is_empty() {
        out.push_str("\nimport type { ");
        for (index, name) in protocol.iter().enumerate() {
            if index != 0 {
                out.push_str(", ");
            }
            out.push_str(name);
        }
        out.push_str(" } from '../atproto.js';\n");
    }
    for module in &imports {
        let _ = writeln!(out, "import type * as {module} from './{module}.js';");
    }
    out.push_str(&body);
    out
}

fn method(
    out: &mut String,
    doc: &Doc,
    name: &str,
    rpc: &Rpc,
    imports: &mut BTreeSet<String>,
    protocol: &mut BTreeSet<&'static str>,
) {
    let ty = type_name(&doc.id, name);
    doc_comment(out, "", rpc.description.as_deref());
    let _ = writeln!(out, "export const {ty}Nsid = '{}' as const;", doc.id);
    if let Some(parameters) = &rpc.parameters {
        out.push('\n');
        object(
            out,
            doc,
            &format!("{ty}Params"),
            None,
            parameters,
            None,
            imports,
            protocol,
        );
    }
    for (suffix, body) in [("Input", &rpc.input), ("Output", &rpc.output)] {
        if let Some(body) = body {
            out.push('\n');
            match &body.schema {
                BodySchema::Object(schema) => {
                    object(
                        out,
                        doc,
                        &format!("{ty}{suffix}"),
                        None,
                        schema,
                        None,
                        imports,
                        protocol,
                    );
                }
                BodySchema::Ref { target } => {
                    let _ = writeln!(
                        out,
                        "export type {ty}{suffix} = {};",
                        reference_type(doc, target, imports)
                    );
                }
            }
        }
    }
}

#[expect(
    clippy::too_many_arguments,
    reason = "imports and protocol gather what the file header needs"
)]
fn object(
    out: &mut String,
    doc: &Doc,
    ty: &str,
    description: Option<&str>,
    o: &Object,
    record: Option<&str>,
    imports: &mut BTreeSet<String>,
    protocol: &mut BTreeSet<&'static str>,
) {
    doc_comment(out, "", description.or(o.description.as_deref()));
    let _ = writeln!(out, "export interface {ty} {{");
    if let Some(nsid) = record {
        let _ = writeln!(out, "  $type: '{nsid}';");
    }
    for (name, field) in &o.properties {
        doc_comment(out, "  ", field.description());
        let optional = if o.required.contains(name) { "" } else { "?" };
        let _ = writeln!(out, "  {name}{optional}: {};", ts_type(doc, field, imports, protocol));
    }
    out.push_str("  /** Fields this version of Motet doesn't know. Kept and written back unchanged. */\n");
    out.push_str("  [extra: string]: unknown;\n}\n");
}

fn ts_type(doc: &Doc, field: &Field, imports: &mut BTreeSet<String>, protocol: &mut BTreeSet<&'static str>) -> String {
    match field {
        Field::String { .. } => "string".to_owned(),
        Field::Integer { .. } => "number".to_owned(),
        Field::Boolean { .. } => "boolean".to_owned(),
        Field::Blob { .. } => {
            protocol.insert("Blob");
            "Blob".to_owned()
        }
        Field::CidLink { .. } => {
            protocol.insert("CidLink");
            "CidLink".to_owned()
        }
        Field::Bytes { .. } => {
            protocol.insert("Bytes");
            "Bytes".to_owned()
        }
        Field::Unknown { .. } => "unknown".to_owned(),
        Field::Ref { target, .. } => reference_type(doc, target, imports),
        Field::Union { refs, closed, .. } => {
            let mut variants = String::new();
            for reference in refs {
                if !variants.is_empty() {
                    variants.push_str(" | ");
                }
                let tag = Target::resolve(&doc.id, reference).reference();
                let _ = write!(
                    variants,
                    "({} & {{ $type: '{tag}' }})",
                    reference_type(doc, reference, imports)
                );
            }
            if !closed {
                if !variants.is_empty() {
                    variants.push_str(" | ");
                }
                variants.push_str("{ $type: string; [extra: string]: unknown }");
            }
            if variants.is_empty() {
                "never".to_owned()
            } else {
                format!("({variants})")
            }
        }
        Field::Array { items, .. } => format!("{}[]", ts_type(doc, items, imports, protocol)),
    }
}

fn reference_type(doc: &Doc, reference: &str, imports: &mut BTreeSet<String>) -> String {
    let target = Target::resolve(&doc.id, reference);
    let name = type_name(&target.doc, &target.def);
    if target.doc == doc.id {
        name
    } else {
        let module = module_name(&target.doc);
        let reference = format!("{module}.{name}");
        imports.insert(module);
        reference
    }
}

fn doc_comment(out: &mut String, indent: &str, text: Option<&str>) {
    if let Some(text) = text {
        let _ = writeln!(out, "{indent}/** {} */", text.replace("*/", "*\\/"));
    }
}
