//! Rust output: one module per lexicon document, serde types, unknown fields kept.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::{BodySchema, Def, Doc, Field, Object, Rpc, Target, module_name, type_name};

const HEADER: &str = "// @generated by motet-lexgen from lexicons/. Do not edit; run `lexgen` in the dev shell.\n";

/// Lexicon descriptions become doc comments as they are. They name NSIDs and
/// fields without backticks, which `doc_markdown` would flag.
const ALLOW_DOC_MARKDOWN: &str =
    "#![allow(clippy::doc_markdown, reason = \"doc comments copy lexicon descriptions, which are not Markdown\")]\n";

/// Generated files, relative to the output directory.
#[must_use]
pub fn generate(docs: &BTreeMap<String, Doc>) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut root = String::from(HEADER);
    root.push('\n');
    for doc in docs.values() {
        let module = module_name(&doc.id);
        let _ = writeln!(root, "pub mod {module};");
        files.push((format!("{module}.rs"), document(doc)));
    }
    // The schemas themselves, for validation at ingest. Paths are relative to
    // crates/lexicons/src/generated/, where this output is checked in.
    root.push_str("\n/// Every lexicon document, by NSID, as JSON text.\npub const SCHEMAS: &[(&str, &str)] = &[\n");
    for doc in docs.values() {
        let path = doc.id.replace('.', "/");
        let _ = writeln!(
            root,
            "    (\"{}\", include_str!(\"../../../../lexicons/{path}.json\")),",
            doc.id
        );
    }
    root.push_str("];\n");
    files.push(("mod.rs".to_owned(), root));
    files
}

fn document(doc: &Doc) -> String {
    let mut out = String::from(HEADER);
    if let Some(d) = &doc.description {
        out.push('\n');
        for line in d.lines() {
            let _ = writeln!(out, "//! {line}");
        }
    }
    for (name, def) in &doc.defs {
        if matches!(def, Def::Space { .. } | Def::PermissionSet { .. }) {
            // A paragraph of its own, so it never lengthens the description's.
            if doc.description.is_some() {
                out.push_str("//!\n");
            }
            let _ = writeln!(
                out,
                "//! `{name}` is host policy metadata, not a wire value; no data type is generated.\n//! Its complete definition remains available in `crate::SCHEMAS`."
            );
        }
    }
    out.push('\n');
    out.push_str(ALLOW_DOC_MARKDOWN);
    if doc.defs.values().any(|def| match def {
        Def::Record { .. } | Def::Object(_) => true,
        Def::Query(rpc) | Def::Procedure(rpc) => {
            rpc.parameters.is_some() || rpc.input.is_some() || rpc.output.is_some()
        }
        _ => false,
    }) {
        out.push_str("\nuse serde::{Deserialize, Serialize};\n");
    }
    for (name, def) in &doc.defs {
        out.push('\n');
        match def {
            Def::Record {
                description,
                key,
                record,
            } => {
                let ty = type_name(&doc.id, name);
                object(
                    &mut out,
                    doc,
                    &ty,
                    description.as_deref().or(record.description.as_deref()),
                    record,
                );
                let _ = write!(
                    out,
                    "\nimpl crate::Record for {ty} {{\n    const NSID: &'static str = \"{}\";\n    const KEY: &'static str = \"{key}\";\n}}\n",
                    doc.id
                );
            }
            Def::Object(o) => object(&mut out, doc, &type_name(&doc.id, name), o.description.as_deref(), o),
            Def::String {
                description,
                known_values,
            } => {
                doc_comment(&mut out, "", description.as_deref());
                if !known_values.is_empty() {
                    let _ = writeln!(out, "/// Known values (not exhaustive): `{known_values:?}`.");
                }
                let _ = writeln!(out, "pub type {} = String;", type_name(&doc.id, name));
            }
            Def::Token { description } => {
                doc_comment(&mut out, "", description.as_deref());
                let ty = type_name(&doc.id, name);
                let _ = writeln!(out, "pub type {ty} = String;");
                let identifier = Target::resolve(&doc.id, &format!("#{name}")).reference();
                let _ = writeln!(out, "pub const {}: &str = {identifier:?};", snake(name).to_uppercase());
            }
            Def::Space { description } | Def::PermissionSet { description } => {
                doc_comment(&mut out, "", description.as_deref());
                let _ = writeln!(out, "pub const NSID: &str = {:?};", doc.id);
            }
            Def::Query(rpc) | Def::Procedure(rpc) => method(&mut out, doc, name, rpc),
            Def::Unsupported => {}
        }
    }
    out
}

fn method(out: &mut String, doc: &Doc, name: &str, rpc: &Rpc) {
    doc_comment(out, "", rpc.description.as_deref());
    let _ = writeln!(out, "pub const NSID: &str = {:?};", doc.id);
    let ty = type_name(&doc.id, name);
    if let Some(parameters) = &rpc.parameters {
        out.push('\n');
        object(
            out,
            doc,
            &format!("{ty}Params"),
            parameters.description.as_deref(),
            parameters,
        );
    }
    for (suffix, body) in [("Input", &rpc.input), ("Output", &rpc.output)] {
        if let Some(body) = body {
            out.push('\n');
            match &body.schema {
                BodySchema::Object(schema) => {
                    object(
                        out,
                        doc,
                        &format!("{ty}{suffix}"),
                        schema.description.as_deref(),
                        schema,
                    );
                }
                BodySchema::Ref { target } => {
                    let _ = writeln!(out, "pub type {ty}{suffix} = {};", reference_type(doc, target));
                }
            }
        }
    }
}

fn object(out: &mut String, doc: &Doc, ty: &str, description: Option<&str>, o: &Object) {
    doc_comment(out, "", description);
    let _ = writeln!(out, "#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]");
    let _ = writeln!(out, "#[serde(rename_all = \"camelCase\")]");
    let _ = writeln!(out, "pub struct {ty} {{");
    let mut nested = String::new();
    for (name, field) in &o.properties {
        doc_comment(out, "    ", field.description());
        if name.eq_ignore_ascii_case(ty) {
            out.push_str(
                "    #[expect(clippy::struct_field_names, reason = \"the field name matches the lexicon property\")]\n",
            );
        }
        let rust_name = snake(name);
        let mut ty = rust_type(&mut nested, doc, field, ty, name);
        if !o.required.contains(name) {
            ty = format!("Option<{ty}>");
            let _ = writeln!(out, "    #[serde(default, skip_serializing_if = \"Option::is_none\")]");
        }
        let _ = writeln!(out, "    pub {}: {ty},", raw(&rust_name));
    }
    out.push_str("    /// Fields this version of Motet doesn't know. Kept and written back unchanged.\n");
    out.push_str("    #[serde(flatten)]\n    pub extra: serde_json::Map<String, serde_json::Value>,\n}\n");
    out.push_str(&nested);
}

fn rust_type(nested: &mut String, doc: &Doc, field: &Field, object_name: &str, property_name: &str) -> String {
    match field {
        Field::String { .. } => "String".to_owned(),
        Field::Integer { .. } => "i64".to_owned(),
        Field::Boolean { .. } => "bool".to_owned(),
        Field::Blob { .. } => "crate::Blob".to_owned(),
        Field::CidLink { .. } => "crate::CidLink".to_owned(),
        Field::Bytes { .. } => "crate::Bytes".to_owned(),
        Field::Unknown { .. } => "serde_json::Value".to_owned(),
        Field::Ref { target, .. } => reference_type(doc, target),
        Field::Union { refs, closed, .. } => {
            let name = format!("{object_name}{}", type_name(&doc.id, property_name));
            union(nested, doc, &name, refs, *closed);
            name
        }
        Field::Array { items, .. } => format!("Vec<{}>", rust_type(nested, doc, items, object_name, property_name)),
    }
}

fn reference_type(doc: &Doc, reference: &str) -> String {
    let target = Target::resolve(&doc.id, reference);
    let name = type_name(&target.doc, &target.def);
    if target.doc == doc.id {
        name
    } else {
        format!("super::{}::{name}", module_name(&target.doc))
    }
}

fn union(out: &mut String, doc: &Doc, ty: &str, refs: &[String], closed: bool) {
    let known = if closed { ty.to_owned() } else { format!("{ty}Known") };
    if !closed {
        let _ = writeln!(
            out,
            "\n/// A tagged union that carries unrecognized variants through unchanged.\n#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(untagged)]\npub enum {ty} {{\n    Known({known}),\n    Unknown {{\n        #[serde(rename = \"$type\")]\n        kind: String,\n        #[serde(flatten)]\n        extra: serde_json::Map<String, serde_json::Value>,\n    }},\n}}"
        );
    }
    let _ = writeln!(
        out,
        "\n#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(tag = \"$type\")]\npub enum {known} {{"
    );
    let variants: Vec<_> = refs
        .iter()
        .map(|reference| {
            let target = Target::resolve(&doc.id, reference);
            let name = type_name(&target.doc, &target.def);
            (target, name)
        })
        .collect();
    let suffix = shared_variant_suffix(&variants);
    for (target, name) in &variants {
        let variant = suffix.and_then(|suffix| name.strip_suffix(suffix)).unwrap_or(name);
        let _ = writeln!(out, "    #[serde(rename = {:?})]", target.reference());
        let _ = write!(out, "    {variant}(");
        if target.doc != doc.id {
            let _ = write!(out, "super::{}::", module_name(&target.doc));
        }
        let _ = writeln!(out, "{name}),");
    }
    out.push_str("}\n");
}

/// Keep variants concise when several referenced types share a trailing word.
/// The complete names still identify payload types and wire tags.
fn shared_variant_suffix(variants: &[(Target, String)]) -> Option<&str> {
    if variants.len() < 3 {
        return None;
    }
    let (_, first) = variants.first()?;
    let (start, _) = first.char_indices().rfind(|(_, character)| character.is_uppercase())?;
    let suffix = first.get(start..)?;
    variants
        .iter()
        .all(|(_, name)| name.len() > suffix.len() && name.ends_with(suffix))
        .then_some(suffix)
}

fn doc_comment(out: &mut String, indent: &str, text: Option<&str>) {
    if let Some(text) = text {
        for line in text.lines() {
            let _ = writeln!(out, "{indent}/// {line}");
        }
    }
}

fn snake(camel: &str) -> String {
    let mut out = String::new();
    for c in camel.chars() {
        if c.is_ascii_uppercase() {
            out.push('_');
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn raw(name: &str) -> String {
    match name {
        "type" | "ref" | "self" | "move" | "match" | "use" | "where" | "mod" | "fn" | "struct" | "enum" => {
            format!("r#{name}")
        }
        _ => name.to_owned(),
    }
}
